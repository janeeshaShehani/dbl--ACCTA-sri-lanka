import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import {
  sendApplicantConfirmation,
  sendAdminNotification,
} from "@/lib/email";

type CorporateApplicationData = {
  id?: string;

  membershipCategory?: string;
  otherLegalEntity?: string;
  residency?: string;
  country?: string;

  registeredName?: string;
  tradingName?: string;
  legalForm?: string;
  registrationNumber?: string;
  registrationDate?: string;
  registrationCountry?: string;
  tinNumber?: string;
  vatNumber?: string;
  website?: string;
  staffCount?: string | number;
  registeredAddress?: string;
  tradingAddress?: string;
  officePhone?: string;
  officialEmail?: string;

  directors?: string;
  shareholders?: string;
  parentFirm?: string;

  services?: string;
  yearsInTaxation?: string | number;
  registrations?: string;
  clientProfile?: string;
  firmProfile?: string;

  nominatedRepresentative?: string;
  nominatedEmail?: string;
  nominatedPhone?: string;

  alternateRepresentative?: string;
  alternateEmail?: string;
  alternatePhone?: string;

  fitAndProperAnswers?: Record<string, string>;
  fitAndProperDetails?: string;

  signatoryOne?: string;
  signatoryTwo?: string;
  resolutionDate?: string;
  declarationAccepted?: boolean;

  totalAmountPaid?: string | number;
  paymentMethod?: string;
  paymentReference?: string;
  paymentDate?: string;

  documents?: Record<
    string,
    {
      name: string;
      path: string;
    } | null
  >;
};

const stringValue = (value: unknown): string | null => {
  if (typeof value !== "string") return null;

  const trimmed = value.trim();

  return trimmed === "" ? null : trimmed;
};

const dateValue = (value: unknown): Date | null => {
  if (typeof value !== "string" || !value.trim()) {
    return null;
  }

  const date = new Date(`${value}T00:00:00`);

  return Number.isNaN(date.getTime()) ? null : date;
};

const numberValue = (value: unknown): number | null => {
  if (value === undefined || value === null || value === "") {
    return null;
  }

  const number = Number(value);

  return Number.isFinite(number) ? number : null;
};

const booleanValue = (value: unknown): boolean | null => {
  if (value === "yes" || value === "Yes" || value === true) {
    return true;
  }

  if (value === "no" || value === "No" || value === false) {
    return false;
  }

  return null;
};

export async function POST(request: Request) {
  try {
    const body = await request.json();

    const application: CorporateApplicationData =
      body.application;

    if (!application || typeof application !== "object") {
      return NextResponse.json(
        { error: "Invalid application data." },
        { status: 400 }
      );
    }

    // Validate required corporate details
    if (
      !stringValue(application.registeredName) ||
      !stringValue(application.registrationNumber) ||
      !stringValue(application.officialEmail) ||
      !stringValue(application.nominatedRepresentative)
    ) {
      return NextResponse.json(
        {
          error: "Please provide the required corporate application details.",
        },
        { status: 400 }
      );
    }

    // Convert residency to Prisma enum
    const residency =
      application.residency === "international"
        ? "INTERNATIONAL"
        : "SRI_LANKA";

    // Application ID generated by frontend
    const applicationId =
      stringValue(application.id) ?? crypto.randomUUID();

    // Corporate application number prefix
    const now = new Date();

    const year = String(now.getFullYear()).slice(-2);
    const month = String(now.getMonth() + 1).padStart(2, "0");

    const registrationPrefix = `CMA${year}${month}`;

    // Prepare document metadata
    const documents = application.documents ?? {};

    const documentRecords = Object.entries(documents)
      .filter(
        ([, file]) =>
          file &&
          typeof file.name === "string" &&
          typeof file.path === "string"
      )
      .map(([documentType, file]) => ({
        documentType,
        originalName: file!.name,
        storedFileName: file!.path.split("/").pop() ?? file!.name,
        filePath: file!.path,
      }));

    
      
      // --------------------------------------------
      // CHECK DUPLICATE CORPORATE EMAIL OR PHONE
      // --------------------------------------------

      const officialEmail = stringValue(application.officialEmail)?.toLowerCase();
      const officePhone = stringValue(application.officePhone);

      const existingApplication =
        await prisma.corporateApplication.findFirst({
          where: {
            OR: [
              ...(officialEmail
                ? [{ officialEmail: { equals: officialEmail } }]
                : []),

              ...(officePhone
                ? [{ officePhone: { equals: officePhone } }]
                : []),
            ],
          },
          select: {
            id: true,
          },
        });

      if (existingApplication) {
        return NextResponse.json(
          {
            success: false,
            duplicate: true,
            error:
              "You are already registered using this company email address or office phone number. Please use different details.",
          },
          { status: 409 }
        );
      }


    // Save application and documents in a transaction
    const result = await prisma.$transaction(async (tx) => {
      // Find existing application numbers
      const existing = await tx.corporateApplication.findMany({
        where: {
          applicationNumber: {
            startsWith: registrationPrefix,
          },
        },
        select: {
          applicationNumber: true,
        },
      });

      // Determine next sequence number
      const highestSequence = existing.reduce(
        (highest, item) => {
          const number = Number(
            item.applicationNumber?.slice(
              registrationPrefix.length
            )
          );

          return Number.isInteger(number)
            ? Math.max(highest, number)
            : highest;
        },
        0
      );

      const applicationNumber =
        `${registrationPrefix}${String(
          highestSequence + 1
        ).padStart(6, "0")}`;

      // Create corporate application
      const savedApplication =
        await tx.corporateApplication.create({
          data: {
            id: applicationId,
            applicationNumber,

            // Section A
            entityType: stringValue(
              application.membershipCategory
            ),
            otherEntityType: stringValue(
              application.otherLegalEntity
            ),
            residency,
            countryOfRegistration: stringValue(
              application.country
            ),

            // Section B
            registeredName: stringValue(
              application.registeredName
            ),
            tradingName: stringValue(
              application.tradingName
            ),
            legalForm: stringValue(application.legalForm),
            registrationNumber: stringValue(
              application.registrationNumber
            ),
            registrationDate: dateValue(
              application.registrationDate
            ),
            registrationCountry: stringValue(
              application.registrationCountry
            ),

            tinNumber: stringValue(application.tinNumber),
            vatNumber: stringValue(application.vatNumber),
            website: stringValue(application.website),
            numberOfEmployees: numberValue(
              application.staffCount
            ),

            registeredAddress: stringValue(
              application.registeredAddress
            ),
            tradingAddress: stringValue(
              application.tradingAddress
            ),

            officePhone: stringValue(
              application.officePhone
            ),
            officialEmail: stringValue(
              application.officialEmail
            ),

            // Section C
            directorsAndKeyOfficers: stringValue(
              application.directors
            ),
            shareholdersAndOwnership: stringValue(
              application.shareholders
            ),
            parentFirmOrGroup: stringValue(
              application.parentFirm
            ),

            // Section D
            servicesOffered: stringValue(
              application.services
            ),
            yearsOfTaxExperience: numberValue(
              application.yearsInTaxation
            ),
            professionalRegistrations: stringValue(
              application.registrations
            ),
            typicalClientProfile: stringValue(
              application.clientProfile
            ),
            briefFirmProfile: stringValue(
              application.firmProfile
            ),

            // Section E
            nominatedRepresentativeName: stringValue(
              application.nominatedRepresentative
            ),
            nominatedRepresentativeEmail: stringValue(
              application.nominatedEmail
            ),
            nominatedRepresentativePhone: stringValue(
              application.nominatedPhone
            ),

            alternateRepresentativeName: stringValue(
              application.alternateRepresentative
            ),
            alternateRepresentativeEmail: stringValue(
              application.alternateEmail
            ),
            alternateRepresentativePhone: stringValue(
              application.alternatePhone
            ),

            // Section F
            fitProperF1: booleanValue(
              application.fitAndProperAnswers?.f1
            ),
            fitProperF2: booleanValue(
              application.fitAndProperAnswers?.f2
            ),
            fitProperF3: booleanValue(
              application.fitAndProperAnswers?.f3
            ),
            fitProperF4: booleanValue(
              application.fitAndProperAnswers?.f4
            ),
            fitProperF5: booleanValue(
              application.fitAndProperAnswers?.f5
            ),
            fitProperF6: booleanValue(
              application.fitAndProperAnswers?.f6
            ),

            fitProperDetails: stringValue(
              application.fitAndProperDetails
            ),

            // Section H
            declarationAccepted:
              application.declarationAccepted ?? false,

            authorisedSignatoryOne: stringValue(
              application.signatoryOne
            ),
            authorisedSignatoryTwo: stringValue(
              application.signatoryTwo
            ),
            resolutionDate: dateValue(
              application.resolutionDate
            ),

            // Section I
            applicationFee:
              residency === "SRI_LANKA" ? 10000 : 100,
            annualSubscription:
              residency === "SRI_LANKA" ? 10000 : 100,
            feeCurrency:
              residency === "SRI_LANKA" ? "LKR" : "USD",

            totalAmountPaid: numberValue(
              application.totalAmountPaid
            ),
            paymentMethod: stringValue(
              application.paymentMethod
            ),
            paymentReference: stringValue(
              application.paymentReference
            ),
            paymentDate: dateValue(
              application.paymentDate
            ),

            status: "SUBMITTED",
            submittedAt: new Date(),
          },
        });

      // Save uploaded documents
      if (documentRecords.length > 0) {
        await tx.corporateDocument.createMany({
          data: documentRecords.map((document) => ({
            applicationId: savedApplication.id,
            documentType: document.documentType,
            originalName: document.originalName,
            storedFileName: document.storedFileName,
            filePath: document.filePath,
          })),
        });
      }

      return savedApplication;
    });

    console.log("Corporate application saved successfully.");
    console.log("Application ID:", result.id);
    console.log(
      "Application Number:",
      result.applicationNumber
    );

        // --------------------------------------------
    // --------------------------------------------
    // STEP 5: Send applicant and admin emails
    // --------------------------------------------
    console.log("CORPORATE APPLICATION EMAIL PROCESS STARTED");

    const applicantEmail =
    result.officialEmail ?? application.officialEmail ?? "";

    const applicantName =
    result.registeredName ?? application.registeredName ?? "Applicant";

    const registrationNumber =
    result.applicationNumber ?? "";

    const membershipCategory =
    application.membershipCategory ?? "Corporate Member";

    if (
    applicantEmail &&
    applicantName &&
    registrationNumber
    ) {
    const emailResults = await Promise.allSettled([
        sendApplicantConfirmation({
        email: applicantEmail,
        name: applicantName,
        applicationType: "corporate",
        registrationNumber,
        membershipCategory,
        }),

        sendAdminNotification({
        name: applicantName,
        email: applicantEmail,
        applicationType: "corporate",
        registrationNumber,
        membershipCategory,
        }),
    ]);

    if (emailResults[0].status === "fulfilled") {
        console.log("Applicant confirmation email sent successfully.");
    } else {
        console.error(
        "Applicant confirmation email failed:",
        emailResults[0].reason
        );
    }

    if (emailResults[1].status === "fulfilled") {
        console.log("Admin notification email sent successfully.");
    } else {
        console.error(
        "Admin notification email failed:",
        emailResults[1].reason
        );
    }
    } else {
    console.error(
        "Email sending skipped: missing applicant email, name, or registration number."
    );
    }

    console.log("CORPORATE APPLICATION EMAIL PROCESS COMPLETED");

    return NextResponse.json(
      {
        success: true,
        message: "Corporate application submitted successfully.",
        applicationId: result.id,
        applicationNumber: result.applicationNumber,
      },
      { status: 201 }
    );
  } catch (error) {
    console.error("Corporate application database error:", error);

    return NextResponse.json(
      {
        error: "Failed to save corporate application.",
      },
      { status: 500 }
    );
  }
}